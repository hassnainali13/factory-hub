/* ─────────────────────────────────────────────
   ACTION BUTTON
───────────────────────────────────────────── */

function ActionButton({ actionLabel, actionLink, onAction, btnClass }) {
  const cls = `rounded-full px-7 py-3 text-sm font-semibold text-white transition-all hover:-translate-y-0.5 active:scale-95 ${btnClass}`;
  return actionLink ? (
    <Link to={actionLink} className={cls}>
      {actionLabel}
    </Link>
  ) : (
    <button onClick={onAction} className={cls}>
      {actionLabel}
    </button>
  );
}

